#!/usr/bin/env python3
"""Generates JRawrCharacterExporterData.lua from JRawr's talent/glyph annotations.

It needs, per class:
  - the Rawr talent-array index for every (tab, row, column) grid position,
  - the Rawr glyph-array index for every English glyph name,
  - the two array lengths, so it can build the compact string stored in the character XML.

Run from the addon repository root with a JRawr checkout next to it:
    python3 tools/addon-data-gen/generate.py
    python3 tools/addon-data-gen/generate.py --check
    python3 tools/addon-data-gen/generate.py --jrawr-dir /path/to/JRawr

The JRawr directory can also be set with JRAWR_DIR.
"""
import argparse
import json
import os
import pathlib
import re
import sys

ADDON_ROOT = pathlib.Path(__file__).resolve().parents[2]
DEFAULT_JRAWR_DIR = ADDON_ROOT.parent / "JRawr"
OUTPUT_NAME = "JRawrCharacterExporterData.lua"

CLASSES = {
    "WarriorTalents": "WARRIOR",
    "PaladinTalents": "PALADIN",
    "HunterTalents": "HUNTER",
    "RogueTalents": "ROGUE",
    "PriestTalents": "PRIEST",
    "DeathKnightTalents": "DEATHKNIGHT",
    "ShamanTalents": "SHAMAN",
    "MageTalents": "MAGE",
    "WarlockTalents": "WARLOCK",
    "DruidTalents": "DRUID",
}

TALENT_RE = re.compile(
    r'@TalentDataAttribute\(index = (\d+), name = "([^"]+)", maxPoints = \d+, '
    r'tree = (\d+), column = (\d+), row = (\d+)'
)
GLYPH_RE = re.compile(r'@GlyphDataAttribute\(index = (\d+), name = "([^"]+)", major = (?:true|false)\)')


def lua_string(value):
    # Glyph/talent names are ASCII; JSON escaping is valid Lua for them.
    return json.dumps(value, ensure_ascii=False)


def fail(message):
    raise SystemExit("addon-data-gen: " + message)


def class_table(talents_dir, java_class, token):
    text = (talents_dir / (java_class + ".java")).read_text(encoding="utf-8")
    data_size = int(re.search(r"private final int\[\] data = new int\[(\d+)\]", text).group(1))
    glyph_size = int(re.search(r"private final boolean\[\] glyphData = new boolean\[(\d+)\]", text).group(1))

    talents = {}
    talent_indexes = []
    for index, name, tree, column, row in TALENT_RE.findall(text):
        index = int(index)
        tab = int(tree) + 1
        row, column = int(row), int(column)
        if not name:
            fail(f"{java_class}: talent {index} has an empty name")
        if tab not in (1, 2, 3):
            fail(f"{java_class}: talent {index} has invalid tree {tree}")
        if not (1 <= row <= 11) or not (1 <= column <= 4):
            fail(f"{java_class}: talent {index} has invalid position row={row} column={column}")
        key = row * 10 + column
        if key in talents.setdefault(tab, {}):
            fail(f"{java_class}: duplicate grid position {key} in tab {tab}")
        talents[tab][key] = index
        talent_indexes.append(index)

    glyphs = {}
    glyph_indexes = []
    for index, name in GLYPH_RE.findall(text):
        index = int(index)
        key = name.lower()
        if not key:
            fail(f"{java_class}: glyph {index} has an empty name")
        if key in glyphs:
            fail(f"{java_class}: duplicate glyph name {name!r}")
        glyphs[key] = index
        glyph_indexes.append(index)

    if sorted(talent_indexes) != list(range(data_size)):
        fail(f"{java_class}: talent indices do not cover 0..{data_size - 1} exactly once")
    if sorted(glyph_indexes) != list(range(glyph_size)):
        fail(f"{java_class}: glyph indices do not cover 0..{glyph_size - 1} exactly once")

    lines = [f"    [{lua_string(token)}] = {{"]
    lines.append(f"        talentCount = {data_size},")
    lines.append(f"        glyphCount = {glyph_size},")
    lines.append("        talents = {")
    for tab in sorted(talents):
        pairs = ", ".join(f"[{k}] = {talents[tab][k]}" for k in sorted(talents[tab]))
        lines.append(f"            [{tab}] = {{ {pairs} }},")
    lines.append("        },")
    lines.append("        glyphs = {")
    for name in sorted(glyphs):
        lines.append(f"            [{lua_string(name)}] = {glyphs[name]},")
    lines.append("        },")
    lines.append("    },")
    return lines


def generate_text(talents_dir):
    lines = [
        "-- Generated by tools/addon-data-gen/generate.py from JRawr's *Talents.java annotations;",
        "-- do not edit by hand.",
        "-- Source: jrawr/rawr-core/src/main/java/rawr/base/talents/*Talents.java",
        "--",
        "-- Why this table is needed: the WoW API identifies talents by (tab, tier, column) and",
        "-- glyphs by English name, while Rawr's compact talent string is indexed by position in",
        "-- each class's Talents.java data/glyphData arrays. This table maps the game's identifiers",
        "-- to those Rawr indices. The values are array indices, not Blizzard spell/talent ids.",
        "--",
        "JRawrCharacterExporterData = {",
    ]
    for java_class, token in CLASSES.items():
        lines.extend(class_table(talents_dir, java_class, token))
    lines.append("}")
    return "\n".join(lines) + "\n"


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--jrawr-dir",
        type=pathlib.Path,
        default=pathlib.Path(os.environ.get("JRAWR_DIR", DEFAULT_JRAWR_DIR)),
        help="JRawr checkout (default: sibling directory or JRAWR_DIR)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed data table is out of date",
    )
    return parser.parse_args(argv)


def main(argv):
    args = parse_args(argv)
    jrawr_dir = args.jrawr_dir.expanduser().resolve()
    talents_dir = jrawr_dir / "jrawr/rawr-core/src/main/java/rawr/base/talents"
    if not talents_dir.is_dir():
        fail(f"JRawr talent sources not found: {talents_dir}; pass --jrawr-dir or set JRAWR_DIR")
    output = ADDON_ROOT / OUTPUT_NAME
    text = generate_text(talents_dir)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != text:
            fail(f"{output} is out of date; run tools/addon-data-gen/generate.py")
        print("up to date:", output)
        return 0
    output.write_text(text, encoding="utf-8")
    print("wrote", output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
